//! Seeded simulations of the bounded command capture (larry#206).
//!
//! Requirement proved: whatever the size of a command's output, the capture keeps
//! the exact first and last bytes of each stream, drops every byte between them and
//! counts those bytes exactly, and one seed always yields one captured trace.
//! Source: tail(1) and head(1), the end of a log is where its error is.

use std::cell::Cell;
use std::ffi::OsStr;
use std::io::{self, Read};
use std::num::TryFromIntError;
use std::os::unix::process::CommandExt;
use std::path::Path;
use std::process::{Command, ExitStatus, Stdio};
use std::sync::mpsc;
use std::time::Duration;

use lgwks_bot::kernel::clock::Clock;
use lgwks_macros::Error;
use lgwks_std::seeded::{DrawError, Seeded};

use super::{
    CAPTURE_CHUNK, Captured, ExecError, HEAD_BYTES, Place, TAIL_BYTES, capture, command_for,
    wait_for_status,
};

/// What every test here returns.
type TestResult = Result<(), Box<dyn std::error::Error>>;

/// Seeds the capture simulation sweeps; each takes one of the output sizes in turn.
const SEEDS: u64 = 18;

/// Bytes a capture keeps in all: its head and its tail.
const KEPT: usize = HEAD_BYTES.saturating_add(TAIL_BYTES);

/// Output sizes the simulation cycles through: empty, one byte, around the head, around
/// the head and the tail together, and past both by a few bytes.
const TOTALS: [usize; 9] = [
    0,
    1,
    HEAD_BYTES.saturating_sub(1),
    HEAD_BYTES,
    HEAD_BYTES.saturating_add(1),
    KEPT.saturating_sub(1),
    KEPT,
    KEPT.saturating_add(1),
    KEPT.saturating_add(TAIL_BYTES).saturating_add(5),
];

/// The byte `Feed` yields at `index`: printable ASCII, so lossy text keeps its length.
fn byte_at(index: usize) -> Result<u8, std::num::TryFromIntError> {
    Ok(b'!'.saturating_add(u8::try_from(index % 90)?))
}

/// A pipe that yields `total` generated bytes in reads of at most `step` bytes.
struct Feed {
    /// Bytes the pipe yields in all.
    total: usize,
    /// Bytes yielded so far.
    position: usize,
    /// The most one read yields.
    step: usize,
}

impl Read for Feed {
    fn read(&mut self, buffer: &mut [u8]) -> io::Result<usize> {
        let left = self.total.saturating_sub(self.position);
        let count = buffer.len().min(self.step).min(left);
        for (offset, slot) in buffer.iter_mut().take(count).enumerate() {
            let index = self.position.saturating_add(offset);
            *slot = byte_at(index).map_err(io::Error::other)?;
        }
        self.position = self.position.saturating_add(count);
        Ok(count)
    }
}

/// The bytes `Feed` yields for `total`, built without the capture under test.
fn stream_of(total: usize) -> Result<Vec<u8>, Box<dyn std::error::Error>> {
    (0..total)
        .map(|index| -> Result<u8, Box<dyn std::error::Error>> { Ok(byte_at(index)?) })
        .collect()
}

/// BLAKE3 of `bytes` through the estate hasher, as 64 hex characters.
fn blake3_hex(bytes: &[u8]) -> String {
    let mut hasher = lgwks_std::hash::Hasher::new();
    hasher.update(bytes);
    hasher.finalize().to_hex()
}

/// A command is launched through the host's session tool, so it starts in a session of its own
/// with no controlling terminal, its leader the spawned pid the ledger and `killpg` name
/// (larry#323); a host without the tool (macOS) keeps the process group and its confinement
/// refuses `/dev/tty` instead.
#[test]
fn sim_a_command_starts_in_a_session_of_its_own() -> TestResult {
    let command = [
        String::from("/bin/sh"),
        String::from("-c"),
        String::from("true"),
    ];
    let (built, program) = command_for(&command, Place::Open(Path::new(".")), "/usr/bin:/bin")?;
    let args: Vec<&OsStr> = built.get_args().collect();
    let tool = "/usr/bin/setsid";
    if Path::new(tool).is_file() {
        assert_eq!(program, tool, "the session tool is the program");
        assert_eq!(built.get_program(), OsStr::new(tool));
        let expected: Vec<&OsStr> = command.iter().map(String::as_str).map(OsStr::new).collect();
        assert_eq!(args, expected, "the command follows the session tool whole");
    } else {
        assert_eq!(program, "/bin/sh", "the command is the program");
        assert_eq!(built.get_program(), OsStr::new("/bin/sh"));
    }
    Ok(())
}

/// A probe place runs its command in the tree but homes it beside the tree, so a
/// tool that initializes a per-user home never writes into the probed tree and
/// its diff; the toolchain homes stay resolved from the host's real home and
/// the child never auto-installs one, while without a host home it keeps no
/// host path at all (larry#274, sixth pass).
#[test]
fn a_probe_place_runs_in_the_tree_but_homes_beside_it() -> TestResult {
    let (built, _) = command_for(
        &[String::from("true")],
        Place::Probe {
            cwd: Path::new("/tree"),
            home: Path::new("/probe-home"),
            rustup_home: Some(Path::new("/host-home/.rustup")),
            cargo_home: Some(Path::new("/host-home/.cargo")),
        },
        "/usr/bin:/bin",
    )?;
    assert_eq!(
        built.get_current_dir(),
        Some(Path::new("/tree")),
        "the probe runs in the tree it reads"
    );
    let env = |name: &str| {
        built
            .get_envs()
            .find_map(|(key, value)| (key == name).then_some(value))
            .flatten()
    };
    assert_eq!(
        env("HOME"),
        Some(OsStr::new("/probe-home")),
        "the probe homes outside the tree it reads"
    );
    assert_eq!(
        env("RUSTUP_HOME"),
        Some(OsStr::new("/host-home/.rustup")),
        "the toolchain home stays resolved from the host's real home"
    );
    assert_eq!(
        env("CARGO_HOME"),
        Some(OsStr::new("/host-home/.cargo")),
        "the cargo home stays resolved from the host's real home"
    );
    assert_eq!(
        env("RUSTUP_AUTO_INSTALL"),
        Some(OsStr::new("0")),
        "a missing toolchain is a fast failure, never a download"
    );
    let (bare, _) = command_for(
        &[String::from("true")],
        Place::Probe {
            cwd: Path::new("/tree"),
            home: Path::new("/probe-home"),
            rustup_home: None,
            cargo_home: None,
        },
        "/usr/bin:/bin",
    )?;
    let bare_env = |name: &str| {
        bare.get_envs()
            .find_map(|(key, value)| (key == name).then_some(value))
            .flatten()
    };
    assert_eq!(
        bare_env("RUSTUP_HOME"),
        None,
        "without a host home the child keeps no host path"
    );
    assert_eq!(
        bare_env("CARGO_HOME"),
        None,
        "without a host home the child keeps no host path"
    );
    assert_eq!(
        bare_env("RUSTUP_AUTO_INSTALL"),
        Some(OsStr::new("0")),
        "the no-install switch holds whatever the host names"
    );
    Ok(())
}

/// Every seed keeps the exact head and tail, counts every dropped byte, and replays one trace.
#[test]
fn sim_capture_keeps_head_and_tail_and_counts_every_dropped_byte() -> TestResult {
    for (seed, &total) in (0..SEEDS).zip(TOTALS.iter().cycle()) {
        let mut stream = Seeded::from_seed(seed);
        let step = usize::try_from(stream.below(8_192)?)?.saturating_add(1);
        let expected = stream_of(total)?;
        let captured = capture(Feed {
            total,
            position: 0,
            step,
        })?;
        let dropped = total.saturating_sub(KEPT);
        assert_eq!(
            captured.dropped,
            u64::try_from(dropped)?,
            "seed {seed}: the dropped count is exact"
        );
        // The report states the stream's own length, and kept plus dropped is all of it: no
        // byte is neither kept nor counted (larry#319).
        assert_eq!(
            captured.bytes,
            u64::try_from(total)?,
            "seed {seed}: every byte the stream yielded is counted"
        );
        let kept = u64::try_from(captured.head.len().saturating_add(captured.tail.len()))?;
        assert_eq!(
            captured.dropped.saturating_add(kept),
            captured.bytes,
            "seed {seed}: kept plus dropped is the bytes the stream yielded"
        );
        let head_end = total.min(HEAD_BYTES);
        assert_eq!(
            captured.head.as_slice(),
            expected.get(..head_end).ok_or("the head range")?,
            "seed {seed}: the head is the first bytes"
        );
        let tail_start = HEAD_BYTES.max(total.saturating_sub(TAIL_BYTES)).min(total);
        assert_eq!(
            captured.tail.as_slice(),
            expected.get(tail_start..).ok_or("the tail range")?,
            "seed {seed}: the tail is the last bytes"
        );
        let (text, reported) = captured.into_text();
        assert_eq!(
            reported,
            u64::try_from(dropped)?,
            "seed {seed}: the text reports the same count"
        );
        if dropped > 0 {
            assert!(
                text.contains(&format!("{dropped} bytes dropped")),
                "seed {seed}: a marker line says how many bytes were dropped"
            );
        }
        assert!(
            text.len() <= KEPT.saturating_add(64),
            "seed {seed}: the kept text stays within the bound plus its marker"
        );
        let (replay, _) = capture(Feed {
            total,
            position: 0,
            step,
        })?
        .into_text();
        assert_eq!(
            blake3_hex(text.as_bytes()),
            blake3_hex(replay.as_bytes()),
            "seed {seed}: the same seed gives the same trace hash"
        );

        // The bound holds after every push, whatever the piece sizes: the tail trims only past
        // twice its size, so head plus tail never exceeds that plus one piece (larry#206 review).
        let mut direct = Captured::default();
        let mut offset = 0_usize;
        while offset < total {
            let piece = usize::try_from(stream.below(8_192)?)?.saturating_add(1);
            let end = offset.saturating_add(piece).min(total);
            direct.push(expected.get(offset..end).ok_or("the piece range")?)?;
            offset = end;
            assert!(
                direct.head.len().saturating_add(direct.tail.len())
                    <= HEAD_BYTES
                        .saturating_add(TAIL_BYTES.saturating_mul(2))
                        .saturating_add(CAPTURE_CHUNK),
                "seed {seed}: head and tail stay within the bound after every push"
            );
        }
    }
    Ok(())
}

/// A cleanup that fails after an earlier refusal keeps that refusal as its source, so the
/// operator sees both causes and neither is flattened into a string (larry#343).
#[test]
fn a_cleanup_refusal_keeps_the_earlier_error_as_its_source() -> TestResult {
    use crate::executor::ExecError;

    let earlier = ExecError::Workspace(io::Error::other("the pipe was not opened"));
    let cleanup = ExecError::cleanup(
        earlier,
        "the child could not be killed",
        ExecError::Reap(io::Error::from(io::ErrorKind::PermissionDenied)),
    );
    let source = std::error::Error::source(&cleanup).ok_or("the earlier refusal is the source")?;
    assert_eq!(
        source.to_string(),
        "exec workspace: the pipe was not opened",
        "the typed cause survives"
    );
    assert!(
        cleanup
            .to_string()
            .contains("the child could not be killed"),
        "the cleanup step is named too: {cleanup}"
    );
    Ok(())
}

/// A reader thread that panics prints the text it carries, never `Any { .. }` (larry#343).
#[test]
fn a_panicking_reader_reports_its_message() {
    let message = std::thread::scope(|scope| {
        let reader = scope.spawn(|| -> io::Result<super::Drained> {
            let explode = std::hint::black_box(true);
            assert!(!explode, "the reader exploded");
            Err(io::Error::other("unreachable"))
        });
        match super::join_reader(reader, "cat") {
            Ok(_drained) => String::from("a panicking reader returned a value"),
            Err(cause) => cause.to_string(),
        }
    });
    assert!(
        message.contains("the reader exploded"),
        "the payload text is printed: {message}"
    );
    assert!(
        !message.contains("Any { .. }"),
        "the payload is never debug-printed: {message}"
    );
}

/// Seeds the command-timeout simulation sweeps.
const WAIT_SEEDS: u64 = 64;

/// The largest virtual step a seed draws, in microseconds: small enough that the real slice each
/// poll waits (never past the virtual time left) stays within a few milliseconds.
const MAX_STEP_US: u64 = 500;

/// The most steps a drawn deadline spans.
const MAX_STEPS: u64 = 12;

/// The polls after which the simulation cancels a wait that ignores the injected clock, so a wait
/// that never reaches its deadline ends in a failed assertion rather than a hang.
const POLL_CAP: u64 = 10_000;

/// Why one command-timeout simulation could not be driven to its assertions.
#[derive(Debug, Error)]
enum WaitSimError {
    /// The seeded stream refused a draw.
    #[error("seeded draw refused: {0}")]
    Draw(#[from] DrawError),
    /// A drawn number or a process id does not fit the type its use needs.
    #[error("number out of range: {0}")]
    Range(#[from] TryFromIntError),
    /// The command could not be started, or its status could not be read.
    #[error("the command failed: {0}")]
    Process(#[from] io::Error),
    /// The wait itself failed.
    #[error("the wait failed: {0}")]
    Wait(#[from] ExecError),
}

/// One seed's wait on a command that never ends by itself, its status held back until the group is
/// killed. Each cancel poll moves a virtual clock by a drawn step and a drawn poll may cancel, so
/// the wait ends on the clock's readings alone: its outcome and its poll count are asserted
/// against the rule worked out here, and the trace is returned for the hash.
fn timeout_trace(seed: u64) -> Result<String, WaitSimError> {
    let mut stream = Seeded::from_seed(seed.wrapping_add(5 << 40));
    let step_us = stream.below(MAX_STEP_US)?.saturating_add(1);
    let steps = stream.below(MAX_STEPS)?.saturating_add(1);
    // The deadline sits on a reading or just before one, so the equal and the strict case both run.
    let deadline_us = step_us
        .saturating_mul(steps)
        .saturating_sub(stream.below(step_us)?);
    // Half the seeds cancel at a drawn poll; the rest never do.
    let cancel_at = match stream.below(2)? {
        0 => POLL_CAP,
        _ => stream.below(steps)?.saturating_add(1),
    };
    let step = Duration::from_micros(step_us);
    let deadline = Duration::from_micros(deadline_us);
    let clock = Clock::virtual_at(Duration::ZERO);
    let polls = Cell::new(0_u64);
    // A refused step cancels: the assertions below then name the clock's reading.
    let cancelled = || {
        let poll = polls.get().saturating_add(1);
        polls.set(poll);
        clock.advance(step).is_err() || poll >= cancel_at
    };
    // A group of its own that this test owns, so the one kill the wait makes ends it.
    let mut command = Command::new("/bin/sh");
    command
        .args(["-c", "exec sleep 20"])
        .process_group(0)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null());
    let mut child = command.spawn()?;
    let pgid = i32::try_from(child.id())?;
    let (status, timed_out, interrupted) =
        std::thread::scope(|scope| -> Result<_, WaitSimError> {
            // The sender stays alive until the command ends, so no status arrives before the kill.
            let (sender, receiver) = mpsc::sync_channel::<io::Result<ExitStatus>>(1);
            scope.spawn(move || sender.send(child.wait()));
            Ok(wait_for_status(
                &clock, &receiver, pgid, deadline, &cancelled,
            )?)
        })?;
    assert!(
        !status?.success(),
        "seed {seed}: the group was killed, not left to finish"
    );
    let expected_polls = deadline_us.div_ceil(step_us);
    let cancelled_first = cancel_at <= expected_polls;
    let want_polls = if cancelled_first {
        cancel_at
    } else {
        expected_polls
    };
    assert_eq!(
        (timed_out, interrupted),
        (!cancelled_first, cancelled_first),
        "seed {seed}: a cancel poll before the deadline's reading wins, else the deadline does"
    );
    assert_eq!(
        polls.get(),
        want_polls,
        "seed {seed}: the wait ended on the first reading it could"
    );
    let reached = Duration::from_micros(step_us.saturating_mul(want_polls));
    assert_eq!(
        clock.now(),
        reached,
        "seed {seed}: the clock moved one step per poll and no other way"
    );
    if timed_out {
        assert!(
            clock.now() >= deadline && clock.now().saturating_sub(step) < deadline,
            "seed {seed}: the timeout flips at the first reading past the deadline, read {:?}",
            clock.now()
        );
    }
    Ok(format!(
        "step_us={step_us} deadline_us={deadline_us} cancel_at={cancel_at} polls={} timed_out={timed_out} interrupted={interrupted} now_us={}",
        polls.get(),
        clock.now().as_micros()
    ))
}

/// The command timeout is decided on the injected clock, never the wall: for every seed a wait
/// with a drawn deadline and a drawn cancel ends at the first reading past the deadline, or at
/// the cancel poll when that comes first, with the group killed, and one seed gives one trace
/// hash (larry#436, SD-4).
#[test]
fn sim_the_command_timeout_decides_on_the_injected_clock() -> TestResult {
    for seed in 0..WAIT_SEEDS {
        let first = blake3_hex(timeout_trace(seed)?.as_bytes());
        let second = blake3_hex(timeout_trace(seed)?.as_bytes());
        assert_eq!(first, second, "seed {seed}: one seed gives one trace hash");
    }
    Ok(())
}
