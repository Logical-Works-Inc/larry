//! Seeded simulations of the bounded command capture (larry#206).
//!
//! Requirement proved: whatever the size of a command's output, the capture keeps
//! the exact first and last bytes of each stream, drops every byte between them and
//! counts those bytes exactly, and one seed always yields one captured trace.
//! Source: tail(1) and head(1), the end of a log is where its error is.

use std::io::{self, Read};

use lgwks_std::seeded::Seeded;

use super::{HEAD_BYTES, TAIL_BYTES, capture};

/// What every test here returns.
type TestResult = Result<(), Box<dyn std::error::Error>>;

/// Seeds the capture simulation sweeps; each takes one of the output sizes in turn.
const SEEDS: u64 = 18;

/// Bytes a capture keeps in all: its head and its tail.
const KEPT: usize = HEAD_BYTES.saturating_add(TAIL_BYTES);

/// Output sizes the simulation cycles through: empty, one byte, around the head, around
/// the head and the tail together, and past both by a few bytes.
const TOTALS: [usize; 9] = [
    0,
    1,
    HEAD_BYTES.saturating_sub(1),
    HEAD_BYTES,
    HEAD_BYTES.saturating_add(1),
    KEPT.saturating_sub(1),
    KEPT,
    KEPT.saturating_add(1),
    KEPT.saturating_add(TAIL_BYTES).saturating_add(5),
];

/// The byte `Feed` yields at `index`: printable ASCII, so lossy text keeps its length.
fn byte_at(index: usize) -> Result<u8, std::num::TryFromIntError> {
    Ok(b'!'.saturating_add(u8::try_from(index % 90)?))
}

/// A pipe that yields `total` generated bytes in reads of at most `step` bytes.
struct Feed {
    /// Bytes the pipe yields in all.
    total: usize,
    /// Bytes yielded so far.
    position: usize,
    /// The most one read yields.
    step: usize,
}

impl Read for Feed {
    fn read(&mut self, buffer: &mut [u8]) -> io::Result<usize> {
        let left = self.total.saturating_sub(self.position);
        let count = buffer.len().min(self.step).min(left);
        for (offset, slot) in buffer.iter_mut().take(count).enumerate() {
            let index = self.position.saturating_add(offset);
            *slot = byte_at(index).map_err(io::Error::other)?;
        }
        self.position = self.position.saturating_add(count);
        Ok(count)
    }
}

/// The bytes `Feed` yields for `total`, built without the capture under test.
fn stream_of(total: usize) -> Result<Vec<u8>, Box<dyn std::error::Error>> {
    (0..total)
        .map(|index| -> Result<u8, Box<dyn std::error::Error>> { Ok(byte_at(index)?) })
        .collect()
}

/// BLAKE3 of `bytes` through the estate hasher, as 64 hex characters.
fn blake3_hex(bytes: &[u8]) -> String {
    let mut hasher = lgwks_std::hash::Hasher::new();
    hasher.update(bytes);
    hasher.finalize().to_hex()
}

/// Every seed keeps the exact head and tail, counts every dropped byte, and replays one trace.
#[test]
fn sim_capture_keeps_head_and_tail_and_counts_every_dropped_byte() -> TestResult {
    for (seed, &total) in (0..SEEDS).zip(TOTALS.iter().cycle()) {
        let mut stream = Seeded::from_seed(seed);
        let step = usize::try_from(stream.below(8_192)?)?.saturating_add(1);
        let expected = stream_of(total)?;
        let captured = capture(Feed {
            total,
            position: 0,
            step,
        })?;
        let dropped = total.saturating_sub(KEPT);
        assert_eq!(
            captured.dropped,
            u64::try_from(dropped)?,
            "seed {seed}: the dropped count is exact"
        );
        let head_end = total.min(HEAD_BYTES);
        assert_eq!(
            captured.head.as_slice(),
            &expected[..head_end],
            "seed {seed}: the head is the first bytes"
        );
        let tail_start = HEAD_BYTES.max(total.saturating_sub(TAIL_BYTES)).min(total);
        assert_eq!(
            captured.tail.as_slice(),
            &expected[tail_start..],
            "seed {seed}: the tail is the last bytes"
        );
        let (text, reported) = captured.into_text();
        assert_eq!(
            reported,
            u64::try_from(dropped)?,
            "seed {seed}: the text reports the same count"
        );
        if dropped > 0 {
            assert!(
                text.contains(&format!("{dropped} bytes dropped")),
                "seed {seed}: a marker line says how many bytes were dropped"
            );
        }
        assert!(
            text.len() <= KEPT.saturating_add(64),
            "seed {seed}: the kept text stays within the bound plus its marker"
        );
        let (replay, _) = capture(Feed {
            total,
            position: 0,
            step,
        })?
        .into_text();
        assert_eq!(
            blake3_hex(text.as_bytes()),
            blake3_hex(replay.as_bytes()),
            "seed {seed}: the same seed gives the same trace hash"
        );
    }
    Ok(())
}
